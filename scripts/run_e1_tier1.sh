#!/bin/bash
# E1 (#148, docs/handicap-concept.md §6): tier-1 handicap sweep at full strength.
#
# gold self-play, 1 000 pairs (2 000 games) per cell, paired duplicate dice.
# Play is 1-ply: the harness (ai/handicap_sweep.py) has no 2-ply mode, and the weighted-dice
# oracle is itself the 1-ply per-roll value. "Full strength" here means the deployed gold net +
# exact bear-off DB at 1-ply, the same setting as phase 1.
#
# Three runs, each with its own baseline (cheap, and the harness asserts it is exactly 50%):
#   1. position: moves first, head start m in {1,2,4,6,8}, each +/- moves first (net estimate column)
#   2. dice:     weighted dice beta in {1,2,4,8,16}, rerolls N in {1,2,3,4}
#   3. combos:   10 combinations of the tier-1 levers (additive-model check)
# then merges them into docs/handicap-e1-tier1.{json,md}.
#
# Usage: scripts/run_e1_tier1.sh   (env: WORKERS=6 PAIRS=1000 MARGIN=0.02 SEED=0 OUT FINAL PY)
# Resumable: a run whose JSON already exists is skipped.
# Runtime estimate (smoke timings under load, 1 worker): weighted-dice pairs ~1.5 s,
# reroll pairs ~0.3 s, position/baseline pairs ~0.1 s  =>  ~6 CPU-hours in all,
# ~1-1.5 h wall on 6 idle workers. Run 2+3 dominate (the weighted-dice cells).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# The venv lives in the main checkout (also when run from a git worktree).
PY="${PY:-$(cd "$(git rev-parse --git-common-dir)/.." && pwd)/.venv/bin/python}"
WORKERS="${WORKERS:-6}"
PAIRS="${PAIRS:-1000}"
MARGIN="${MARGIN:-0.02}"
SEED="${SEED:-0}"
OUT="${OUT:-docs/e1-tier1}"               # per-run JSON + markdown
FINAL="${FINAL:-docs/handicap-e1-tier1}"  # merged .json + .md
mkdir -p "$OUT"

GAMES=$((2 * PAIRS))
COMMON=(--games "$GAMES" --workers "$WORKERS" --seed "$SEED" --margin "$MARGIN")

POSITION_COMBOS="pip_headstart:6,pip_headstart:8,pip_headstart:1+first_mover,pip_headstart:2+first_mover,pip_headstart:4+first_mover,pip_headstart:6+first_mover,pip_headstart:8+first_mover"

COMBOS="weighted_dice:2+first_mover,\
weighted_dice:4+first_mover,\
rerolls:2+first_mover,\
weighted_dice:2+rerolls:2,\
weighted_dice:4+rerolls:2,\
weighted_dice:2+pip_headstart:4,\
rerolls:2+pip_headstart:4,\
weighted_dice:2+rerolls:1+first_mover,\
weighted_dice:4+rerolls:2+first_mover,\
weighted_dice:8+rerolls:4+pip_headstart:4+first_mover"

run() {  # name, extra args...
  local name="$1"; shift
  if [ -f "$OUT/$name.json" ]; then
    echo "== $name: $OUT/$name.json exists, skipping (delete it to rerun)"
    return
  fi
  echo "== $name  ($(date '+%H:%M'))"
  "$PY" main.py handicap-sweep "${COMMON[@]}" "$@" --out "$OUT/$name.json"
}

run position --only first_mover,pip_headstart --combos "$POSITION_COMBOS"
run dice     --only weighted_dice,rerolls --no-combos
run combos   --only first_mover --combos "$COMBOS"

"$PY" - "$OUT" "$FINAL" <<'EOF'
"""Merge the three runs into one table with the additive (log-odds) model per combination."""
import json, math, sys
out, final = sys.argv[1], sys.argv[2]
cells, meta = {}, {}
for name in ("position", "dice", "combos"):
    with open(f"{out}/{name}.json") as f:
        p = json.load(f)
    meta[name] = {k: v for k, v in p.items() if k != "cells"}
    for c in p["cells"]:
        cells.setdefault(c["label"], c)
logit = lambda p: math.log(min(max(p, 1e-6), 1 - 1e-6) / (1 - min(max(p, 1e-6), 1 - 1e-6)))
sig = lambda x: 1 / (1 + math.exp(-x))
for c in cells.values():
    parts = [f"{k}:{int(x) if float(x).is_integer() else x}" for k, x in c["cell"]]
    c["additive"] = None
    if len(parts) > 1 and all(p in cells for p in parts):
        c["additive"] = sig(sum(logit(cells[p]["rate"]) for p in parts))
rows = sorted(cells.values(), key=lambda s: (s["rate"], s["label"]))
L = ["| handicap | handicapped-side win % [95% CI] | shift (pp) | net est. % | additive % | games | mean plies | mean rerolls |",
     "|---|---|---|---|---|---|---|---|"]
for s in rows:
    est = "" if s.get("net_estimate") is None else f"{100*s['net_estimate']:.1f}"
    add = "" if s["additive"] is None else f"{100*s['additive']:.1f}"
    L.append(f"| `{s['label']}` | {100*s['rate']:.1f} [{100*s['ci_lo']:.1f}, {100*s['ci_hi']:.1f}] "
             f"| {100*(s['rate']-0.5):+.1f} | {est} | {add} | {s['games']} | {s['mean_plies']:.0f} "
             f"| {s.get('mean_rerolls', 0):.2f} |")
with open(final + ".json", "w") as f:
    json.dump({"runs": meta, "cells": rows}, f, indent=1)
with open(final + ".md", "w") as f:
    f.write("# E1 tier-1 sweep (#148)\n\n"
            "Generated by `scripts/run_e1_tier1.sh`: gold self-play, 1-ply, paired duplicate dice. "
            "*net est.* = the net's start-position estimate (position levers only); "
            "*additive* = combination predicted from its singles in log-odds.\n\n")
    f.write("\n".join(L) + "\n")
print("\n".join(L))
print(f"\nWrote {final}.json and {final}.md")
EOF
